// The Project window's list of each project's files (editor/project/files.bend reads it).
//
// A Bend program cannot list a folder, so this file does, as tools/shaders/catalog.js does for
// shaders: it writes editor/project/files_generated.bend, one list of paths per project folder,
// each path inside the project's folder ("shaders/ripples.frag.glsl"), an empty folder as
// "name/". `bun run dev`, `check` and `build` write it. The dev server lists a project again
// with listProject after the editor makes a folder in it (tools/dev.ts).
//
// Limits now:
// - The list is written when the dev server starts: a file added by hand while it runs shows
//   after a restart (or a folder made in the editor).

import { readdirSync, renameSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const SKIP = new Set([".DS_Store", "Thumbs.db"]);

// Every file under a project's folder, inside it, sorted; an empty folder ends in "/".
export function listFolder(dir) {
  const out = [];
  const walk = (dir, above) => {
    const names = readdirSync(dir).filter((n) => !SKIP.has(n)).sort();
    if (names.length === 0 && above) out.push(above + "/");
    for (const name of names) {
      const path = above ? `${above}/${name}` : name;
      if (statSync(join(dir, name)).isDirectory()) walk(join(dir, name), path);
      else out.push(path);
    }
  };
  walk(dir, "");
  return out;
}

// A sample's files, by its folder name under projects/.
export function listProject(folder, root = resolve("projects")) {
  return listFolder(join(root, folder));
}

const quote = (s) => JSON.stringify(s);

// The module that gives each project's files by its folder name, from [folder, paths] pairs.
export function filesText(projects) {
  let picks = "[]";
  for (const [f, list] of [...projects].reverse()) {
    const paths = list.map(quote).join(",\n    ");
    picks = `pick(String.eq(folder, ${quote(f)}), [\n    ${paths}],\n  ${picks})`;
  }
  return `# GENERATED by tools/project/files.js from projects/*. Do not edit: bun run dev, build and
# check write this file again. Each project's files, inside its folder (editor/project/files.bend).

import Base

def pick(c: Bool, a: List<&2, String>, b: List<&2, String>) -> List<&2, String>:
  match c:
    case True{}:
      a
    case False{}:
      b

# The files of a project's folder; none for a folder that is not a project's.
def of(+folder: String) -> List<&2, String>:
  ${picks}
`;
}

// Writes the samples' files (every folder under root) into out.
export function writeProjectFiles(root = resolve("projects"), out = resolve("editor/project/files_generated.bend")) {
  const folders = readdirSync(root).filter((d) => statSync(join(root, d)).isDirectory()).sort();
  const text = filesText(folders.map((f) => [f, listProject(f, root)]));
  writeFileSync(`${out}.${process.pid}.tmp`, text);
  renameSync(`${out}.${process.pid}.tmp`, out);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  writeProjectFiles();
}
